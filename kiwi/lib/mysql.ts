import { chmodSync, chownSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { join } from "node:path";
import { agent, registerSecret, sealSecret, unsealSecret } from "./host";

// MySQL for kiwi. The server binary comes from the system image
// (apt-get install mysql-server); everything that belongs to the user lives
// on user.img, mounted at /www inside the isolation:
//
//   /www/db/my.cnf       server config (the isol "mysql" unit only starts when it exists)
//   /www/db/mysql/       data directory
//   /www/db/log/         error log
//   /www/db/files/       secure_file_priv (LOAD DATA / SELECT ... INTO OUTFILE)
//   /www/db/credentials.json  per-database user and password (sealed), for "Show password"
//   /www/password.txt    root password, sealed with the host-only key
//   /www/redir.json      { "mysql_password": "password.txt" } for `kiwin get`
//
// Every new storage (user.img) gets a fresh data directory and root password.

const STORAGE = "/www";
const DB_DIR = join(STORAGE, "db");
const CNF = join(DB_DIR, "my.cnf");
const DATA_DIR = join(DB_DIR, "mysql");
const LOG_DIR = join(DB_DIR, "log");
const FILES_DIR = join(DB_DIR, "files");
const PASSWORD_FILE = join(STORAGE, "password.txt");
const CREDENTIALS = join(DB_DIR, "credentials.json");
/** Name under which the root password is listed in /www/redir.json (`kiwin get mysql_password`). */
const SECRET_NAME = "mysql_password";
const SOCKET = "/run/mysqld/mysqld.sock";
const MYSQLD = "/usr/sbin/mysqld";
const UNIT = "mysql";

const SYSTEM_SCHEMAS = ["information_schema", "mysql", "performance_schema", "sys"];
/** A statement in an imported dump that switches to or recreates a system schema. */
const SYSTEM_SCHEMA_SQL = /^\s*(?:USE|CREATE\s+(?:DATABASE|SCHEMA)|DROP\s+(?:DATABASE|SCHEMA))\b[^;\n]*?[\s`/](?:mysql|sys|performance_schema|information_schema)`?(?=[\s;/])/im;

export interface DatabaseInfo {
    name: string;
    /** Users with privileges on it (user@host). */
    users: string[];
    /** User whose password kiwi has stored, if any. */
    savedUser: string | null;
    sizeBytes: number;
    tables: number;
}

interface StoredCredential {
    user: string;
    host: string;
    /** Sealed with the host key. */
    password: string;
    updatedAt: string;
}
const NAME = /^[A-Za-z0-9_]{1,64}$/;

const MY_CNF = `# Generated by kiwi. Lives on user.img so it moves with the data.
[mysqld]
user = mysql
datadir = ${DATA_DIR}
socket = ${SOCKET}
pid-file = /run/mysqld/mysqld.pid
port = 3306
bind-address = 127.0.0.1
log-error = ${LOG_DIR}/error.log
secure_file_priv = ${FILES_DIR}

[client]
socket = ${SOCKET}
`;

const quote = (s: string) => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

function checkName(kind: string, name: string) {
    if (!NAME.test(name)) throw new Error(`invalid ${kind} name ${JSON.stringify(name)} (letters, digits, _ only)`);
}

function run(cmd: string[]) {
    const p = Bun.spawnSync(cmd, { stdout: "pipe", stderr: "pipe" });
    return { code: p.exitCode, out: p.stdout.toString().trim(), err: p.stderr.toString().trim() };
}

function mysqlIds(): { uid: number; gid: number } {
    const uid = Number(run(["id", "-u", "mysql"]).out);
    const gid = Number(run(["id", "-g", "mysql"]).out);
    if (!Number.isInteger(uid) || !Number.isInteger(gid) || uid <= 0) throw new Error("system user 'mysql' not found");
    return { uid, gid };
}

export class KiwiMysql {
    /** Last error from setup()/ensure(), for showing in the UI. */
    static lastError: string | null = null;

    /** mysql-server is installed in the system image. */
    static isInstalled(): boolean {
        return existsSync(MYSQLD) && existsSync("/usr/bin/mysql");
    }

    /** /www is a mounted user.img (never put user data into the system image). */
    static isStorageMounted(): boolean {
        return readFileSync("/proc/self/mountinfo", "utf8")
            .split("\n")
            .some((line) => line.split(" ")[4] === STORAGE);
    }

    /** This storage already has a kiwi MySQL instance. */
    static isSetup(): boolean {
        return existsSync(CNF) && existsSync(join(DATA_DIR, "mysql.ibd")) && existsSync(PASSWORD_FILE);
    }

    /**
     * Set MySQL up on the current storage if it is not yet, and make sure the
     * server runs. Call it on kiwi start and after KiwiImg.create().
     */
    static async ensure(): Promise<boolean> {
        this.lastError = null;
        if (!this.isInstalled()) return this.fail("MySQL is not installed in the system image (apt-get install mysql-server)");
        if (!this.isStorageMounted()) return this.fail(`user storage is not mounted at ${STORAGE}; refusing to put data in the system image`);
        if (!this.isSetup()) return this.setup();
        try {
            this.harden();
            registerSecret(SECRET_NAME, "password.txt");
            await agent(`/units/${UNIT}/start`, {});
            await this.waitReady();
            return true;
        } catch (e) {
            return this.fail((e as Error).message);
        }
    }

    /**
     * Initialise a fresh MySQL instance on /www/db with a new random root
     * password, sealed into /www/password.txt. Rolls back on failure.
     */
    static async setup(): Promise<boolean> {
        this.lastError = null;
        if (!this.isInstalled()) return this.fail("MySQL is not installed in the system image (apt-get install mysql-server)");
        if (!this.isStorageMounted()) return this.fail(`user storage is not mounted at ${STORAGE}; refusing to put data in the system image`);
        if (this.isSetup()) return true;
        if (existsSync(DATA_DIR) && readdirSync(DATA_DIR).length > 0) {
            return this.fail(`${DATA_DIR} exists but is not a kiwi MySQL setup; not touching it`);
        }

        const created: string[] = [];
        const make = (dir: string, owner: { uid: number; gid: number } | null, mode: number) => {
            if (!existsSync(dir)) {
                mkdirSync(dir, { mode });
                created.push(dir);
            }
            if (owner) chownSync(dir, owner.uid, owner.gid);
            chmodSync(dir, mode);
        };

        try {
            const owner = mysqlIds();
            // root:mysql 0750: mysqld can reach its data, nginx (www-data) can't even list it.
            make(DB_DIR, { uid: 0, gid: owner.gid }, 0o750);
            make(DATA_DIR, owner, 0o750);
            make(LOG_DIR, owner, 0o750);
            make(FILES_DIR, owner, 0o750);
            writeFileSync(CNF, MY_CNF, { mode: 0o640 });
            chownSync(CNF, 0, owner.gid);
            created.push(CNF);

            const init = run([MYSQLD, `--defaults-file=${CNF}`, "--initialize-insecure"]);
            if (init.code !== 0) throw new Error(`mysqld --initialize failed: ${this.errorLogTail() || init.err}`);

            // Seal first: if the host key is unavailable we fail before the
            // password is set, so it can never be lost.
            const password = randomBytes(24).toString("base64url");
            const sealed = await sealSecret(password);

            await agent(`/units/${UNIT}/start`, {});
            await this.waitReady();
            await this.exec(`ALTER USER 'root'@'localhost' IDENTIFIED BY ${quote(password)};`, "");

            writeFileSync(PASSWORD_FILE, sealed + "\n", { mode: 0o600 });
            created.push(PASSWORD_FILE);
            registerSecret(SECRET_NAME, "password.txt");
            return true;
        } catch (e) {
            await agent(`/units/${UNIT}/stop`, {}).catch(() => {});
            for (const p of created.reverse()) rmSync(p, { recursive: true, force: true });
            return this.fail((e as Error).message);
        }
    }

    /** Decrypted root password of the current storage. */
    static async rootPassword(): Promise<string> {
        return unsealSecret(readFileSync(PASSWORD_FILE, "utf8").trim());
    }

    /** State of the isol "mysql" unit (running, pid, uptime, ...). */
    static async status() {
        return agent<{ state: string; pid: number | null; uptime: number | null; error: string | null }>(`/units/${UNIT}`);
    }

    static async listDatabases(): Promise<string[]> {
        const rows = await this.query("SHOW DATABASES;");
        return rows.map((r) => r[0]).filter((d) => !SYSTEM_SCHEMAS.includes(d));
    }

    /** User databases with their users, size and table count. */
    static async databaseInfo(): Promise<DatabaseInfo[]> {
        const names = await this.listDatabases();
        const sizes = new Map<string, [number, number]>();
        for (const [db, bytes, tables] of await this.query(
            "SELECT table_schema, COALESCE(SUM(data_length + index_length), 0), COUNT(*) FROM information_schema.tables GROUP BY table_schema;",
        )) sizes.set(db, [Number(bytes) || 0, Number(tables) || 0]);
        const users = new Map<string, string[]>();
        for (const [db, user, host] of await this.query("SELECT Db, User, Host FROM mysql.db;")) {
            const name = db.replace(/\\_/g, "_");
            users.set(name, [...(users.get(name) ?? []), `${user}@${host}`]);
        }
        const saved = this.readCredentials();
        return names.map((name) => ({
            name,
            users: users.get(name) ?? [],
            savedUser: saved[name]?.user ?? null,
            sizeBytes: sizes.get(name)?.[0] ?? 0,
            tables: sizes.get(name)?.[1] ?? 0,
        }));
    }

    // ---- Stored per-database credentials ----

    private static readCredentials(): Record<string, StoredCredential> {
        try {
            return JSON.parse(readFileSync(CREDENTIALS, "utf8"));
        } catch {
            return {};
        }
    }

    private static writeCredentials(all: Record<string, StoredCredential>) {
        writeFileSync(`${CREDENTIALS}.tmp`, JSON.stringify(all, null, 2) + "\n", { mode: 0o600 });
        chownSync(`${CREDENTIALS}.tmp`, 0, 0);
        renameSync(`${CREDENTIALS}.tmp`, CREDENTIALS);
    }

    /** Remember (sealed) the password of a database's user, so it can be shown again. */
    static async saveCredential(database: string, user: string, password: string, host = "localhost"): Promise<void> {
        checkName("database", database);
        const all = this.readCredentials();
        all[database] = { user, host, password: await sealSecret(password), updatedAt: new Date().toISOString() };
        this.writeCredentials(all);
    }

    static forgetCredential(database: string): void {
        const all = this.readCredentials();
        if (!(database in all)) return;
        delete all[database];
        this.writeCredentials(all);
    }

    /** Stored user and decrypted password of a database, or null if kiwi never stored one. */
    static async credential(database: string): Promise<{ user: string; host: string; password: string } | null> {
        const c = this.readCredentials()[database];
        if (!c) return null;
        return { user: c.user, host: c.host, password: await unsealSecret(c.password) };
    }

    /** User kiwi manages for a database: the stored one, else the user named like the database. */
    static managedUser(database: string): string {
        return this.readCredentials()[database]?.user ?? database;
    }

    /**
     * Set the password of a database's user, creating the user with full
     * access to the database if it does not exist (e.g. after an import).
     */
    static async setDatabasePassword(database: string, user: string, password: string, host = "localhost"): Promise<void> {
        checkName("database", database);
        checkName("user", user);
        if (user === "root" || user.startsWith("mysql")) throw new Error(`refusing to manage the ${user} user`);
        const who = `${quote(user)}@${quote(host)}`;
        await this.exec(
            `CREATE USER IF NOT EXISTS ${who} IDENTIFIED BY ${quote(password)}; ` +
            `ALTER USER ${who} IDENTIFIED BY ${quote(password)}; ` +
            `GRANT ALL PRIVILEGES ON \`${database}\`.* TO ${who};`,
        );
        await this.saveCredential(database, user, password, host);
    }

    // ---- Import / export ----

    /**
     * mysqldump of one database, or (null) of every user database. System
     * schemas are never included, so an import cannot replace the root user.
     * The caller streams `stdout`; `done` resolves to an error message or null.
     */
    static async dump(database: string | null): Promise<{ stdout: ReadableStream<Uint8Array>; done: Promise<string | null> }> {
        const names = await this.listDatabases();
        if (database !== null && !names.includes(database)) throw new Error(`no database ${database}`);
        const targets = database === null ? names : [database];
        if (targets.length === 0) throw new Error("there are no databases to export");
        const client = await this.clientConfig();
        const p = Bun.spawn([
            "mysqldump", `--defaults-extra-file=${client.file}`,
            "--single-transaction", "--routines", "--triggers", "--events", "--hex-blob", "--no-tablespaces",
            "--set-gtid-purged=OFF", "--default-character-set=utf8mb4",
            // One database: plain dump, importable into any name. All: with CREATE DATABASE / USE.
            ...(database === null ? ["--databases", ...targets] : [targets[0]]),
        ], { stdout: "pipe", stderr: "pipe" });
        const done = Promise.all([new Response(p.stderr).text(), p.exited]).then(([err, code]) => {
            client.remove();
            return code === 0 ? null : err.trim() || `mysqldump exited ${code}`;
        });
        return { stdout: p.stdout as ReadableStream<Uint8Array>, done };
    }

    /** mysqldump of a single table (the MySQL Manager's table export). */
    static async dumpTable(database: string, table: string): Promise<{ stdout: ReadableStream<Uint8Array>; done: Promise<string | null> }> {
        const client = await this.clientConfig();
        const p = Bun.spawn([
            "mysqldump", `--defaults-extra-file=${client.file}`,
            "--single-transaction", "--triggers", "--hex-blob", "--no-tablespaces", "--set-gtid-purged=OFF", "--default-character-set=utf8mb4",
            "--", database, table,
        ], { stdout: "pipe", stderr: "pipe" });
        const done = Promise.all([new Response(p.stderr).text(), p.exited]).then(([err, code]) => {
            client.remove();
            return code === 0 ? null : err.trim() || `mysqldump exited ${code}`;
        });
        return { stdout: p.stdout as ReadableStream<Uint8Array>, done };
    }

    /**
     * Feed a .sql dump to the server, into `database` or (null) into whatever
     * databases the dump creates. Stops at any statement that touches a system
     * schema (a full-server dump would otherwise replace kiwi's root user).
     */
    static async restore(database: string | null, sql: ReadableStream<Uint8Array>): Promise<{ bytes: number }> {
        if (database !== null) {
            checkName("database", database);
            if (!(await this.listDatabases()).includes(database)) throw new Error(`no database ${database}`);
        }
        const client = await this.clientConfig();
        const p = Bun.spawn([
            "mysql", `--defaults-extra-file=${client.file}`, "--default-character-set=utf8mb4", "--binary-mode",
            ...(database ? [database] : []),
        ], { stdin: "pipe", stdout: "ignore", stderr: "pipe" });
        const stderr = new Response(p.stderr).text();
        let bytes = 0;
        let refused: string | null = null;
        let tail = "";
        const dec = new TextDecoder();
        const reader = sql.getReader();
        try {
            for (;;) {
                const { done, value: chunk } = await reader.read();
                if (done) break;
                // Check whole lines only; keep the unfinished last line for the next chunk.
                const text = tail + dec.decode(chunk, { stream: true });
                const cut = text.lastIndexOf("\n");
                const lines = cut >= 0 ? text.slice(0, cut + 1) : "";
                tail = cut >= 0 ? text.slice(cut + 1) : text;
                if (tail.length > 1024 * 1024) tail = tail.slice(-4096); // huge INSERT lines can't be a USE statement
                const m = SYSTEM_SCHEMA_SQL.exec(lines);
                if (m) {
                    refused = m[0].trim();
                    break;
                }
                if (p.exitCode !== null) break; // mysql gave up; its error is on stderr
                try {
                    p.stdin.write(chunk);
                    await p.stdin.flush();
                } catch {
                    break;
                }
                bytes += chunk.length;
            }
            if (!refused && SYSTEM_SCHEMA_SQL.test(tail)) refused = tail.trim();
        } finally {
            reader.cancel().catch(() => {});
            if (refused) p.kill();
            else await Promise.resolve(p.stdin.end()).catch(() => {});
        }
        const [err, code] = await Promise.all([stderr, p.exited]);
        client.remove();
        if (refused) throw new Error(`stopped at "${refused.slice(0, 80)}": dumps must not touch MySQL's system schemas (export only your own databases)`);
        if (code !== 0) throw new Error(err.trim() || `mysql exited ${code}`);
        return { bytes };
    }

    static async createDatabase(name: string): Promise<void> {
        checkName("database", name);
        await this.exec(`CREATE DATABASE \`${name}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;`);
    }

    static async dropDatabase(name: string): Promise<void> {
        checkName("database", name);
        if (SYSTEM_SCHEMAS.includes(name.toLowerCase())) throw new Error(`refusing to drop ${name}`);
        await this.exec(`DROP DATABASE \`${name}\`;`);
    }

    /** Create a user with full access to `database` (if given). Host defaults to localhost. */
    static async createUser(user: string, password: string, database?: string, host = "localhost"): Promise<void> {
        checkName("user", user);
        if (database) checkName("database", database);
        let sql = `CREATE USER ${quote(user)}@${quote(host)} IDENTIFIED BY ${quote(password)};`;
        if (database) sql += ` GRANT ALL PRIVILEGES ON \`${database}\`.* TO ${quote(user)}@${quote(host)};`;
        await this.exec(sql);
    }

    static async dropUser(user: string, host = "localhost"): Promise<void> {
        checkName("user", user);
        if (user === "root" || user.startsWith("mysql")) throw new Error(`refusing to drop ${user}`);
        await this.exec(`DROP USER ${quote(user)}@${quote(host)};`);
    }

    static async setUserPassword(user: string, password: string, host = "localhost"): Promise<void> {
        checkName("user", user);
        if (user === "root") throw new Error("the root password is managed by kiwi");
        await this.exec(`ALTER USER ${quote(user)}@${quote(host)} IDENTIFIED BY ${quote(password)};`);
    }

    /** Run SQL as root and return rows (tab-separated columns). */
    static async query(sql: string): Promise<string[][]> {
        const out = await this.exec(sql);
        return out ? out.split("\n").map((l) => l.split("\t")) : [];
    }

    /**
     * Run SQL as root through the mysql client. The SQL goes over stdin and the
     * password through a 0600 file on tmpfs, so neither shows up in `ps`.
     */
    private static async exec(sql: string, password?: string): Promise<string> {
        const client = await this.clientConfig(password);
        try {
            const p = Bun.spawn(["mysql", `--defaults-extra-file=${client.file}`, "--batch", "--raw", "--skip-column-names"], {
                stdin: new Blob([sql]),
                stdout: "pipe",
                stderr: "pipe",
            });
            const [out, err, code] = await Promise.all([new Response(p.stdout).text(), new Response(p.stderr).text(), p.exited]);
            if (code !== 0) throw new Error(err.trim() || `mysql exited ${code}`);
            return out.trimEnd();
        } finally {
            client.remove();
        }
    }

    /** Root client options in a 0600 file on tmpfs; call remove() when the client exits. */
    private static async clientConfig(password?: string): Promise<{ file: string; remove: () => void }> {
        const pw = password ?? (await this.rootPassword());
        const dir = mkdtempSync("/run/kiwi-mysql-");
        const file = join(dir, "client.cnf");
        writeFileSync(file, `[client]\nuser=root\npassword=${quote(pw)}\nsocket=${SOCKET}\n`, { mode: 0o600 });
        return { file, remove: () => rmSync(dir, { recursive: true, force: true }) };
    }

    private static async waitReady(timeoutMs = 60_000) {
        const until = Date.now() + timeoutMs;
        while (Date.now() < until) {
            // ping exits 0 whenever the server answers, even with "access denied".
            if (existsSync(SOCKET) && run(["mysqladmin", `--socket=${SOCKET}`, "--connect-timeout=2", "ping"]).code === 0) return;
            await Bun.sleep(500);
        }
        throw new Error(`MySQL did not become ready: ${this.errorLogTail() || "timeout"}`);
    }

    /**
     * Keep secrets and MySQL files away from other users inside the isolation
     * (nginx workers run as www-data). Also fixes storage set up by older kiwi.
     */
    private static harden() {
        const { gid } = mysqlIds();
        chownSync(DB_DIR, 0, gid);
        chmodSync(DB_DIR, 0o750);
        chownSync(CNF, 0, gid);
        chmodSync(CNF, 0o640);
        for (const f of [PASSWORD_FILE, CREDENTIALS, "/www/redir.json"]) {
            if (existsSync(f)) {
                chownSync(f, 0, 0);
                chmodSync(f, 0o600);
            }
        }
    }

    private static errorLogTail(): string {
        try {
            return readFileSync(join(LOG_DIR, "error.log"), "utf8").trim().split("\n").slice(-5).join("\n");
        } catch {
            return "";
        }
    }

    private static fail(message: string): false {
        this.lastError = message;
        return false;
    }
}
